export function fareBill(rideId: number, extras: Record<string, number>, approved = false): FareBill {
  const pkg = 5200;
  const extraKm = Math.max(0, (extras.end_odo ?? 0) - (extras.start_odo ?? 0) - 100);
  const extraKmAmt = extraKm * 14;
  const waiting = Math.max(0, (extras.waiting_min ?? 0) - 30) * 2;
  const lines = [
    { label: 'Package fare', amount: pkg },
    { label: `Extra ${extraKm} km`, amount: extraKmAmt },
    { label: 'Toll', amount: extras.toll ?? 0 },
    { label: 'Extra toll', amount: extras.extra_toll ?? 0 },
    { label: `Waiting, ${Math.max(0, (extras.waiting_min ?? 0) - 30)} min`, amount: waiting },
    { label: 'Driver allowance', amount: extras.allowance ?? 0 },
    { label: 'Night charge (12 AM to 3:30 AM)', amount: null, note: 'AOLO will add' },
  ];
  const total = lines.reduce((s, l) => s + (l.amount ?? 0), 0);
  return {
    ride_id: rideId,
    title: `Outstation round trip · ${100 + extraKm} km`,
    lines,
    total,
    commission_note: `AOLO commission 15% on fare and extra km: ₹${Math.round((pkg + extraKmAmt) * 0.15)}`,
    steps: [
      { label: 'You submitted the bill', state: 'done' },
      { label: 'Rider approves the extras', state: approved ? 'done' : 'waiting' },
      { label: 'AOLO adds night charge', state: approved ? 'done' : 'pending' },
      { label: 'Collect the final amount', state: approved ? 'waiting' : 'pending' },
    ],
    can_collect: approved,
  };
}

export function assertOtp(otp: string, expected: string) {
  // Mock accepts the seeded OTP or any 6/4 digit code during development.
  if (!/^\d{4,6}$/.test(otp)) throw new ApiError('Enter a valid OTP', 422, { otp: 'Enter a valid OTP' });
  void expected;
}
